package com.joysistvi.stage1.day12;

public class Activity11_Menorca {

    public static void main(String[] args) {

        // 1. Math.abs()
        // Returns the absolute value of a number.
        // Example: -10 becomes 10.
        System.out.println("Math.abs(): " + Math.abs(-10));


        // 2. Math.max()
        // Returns the larger value between two numbers.
        // Example: between 10 and 20, the maximum is 20.
        System.out.println("Math.max(): " + Math.max(10, 20));


        // 3. Math.min()
        // Returns the smaller value between two numbers.
        // Example: between 10 and 20, the minimum is 10.
        System.out.println("Math.min(): " + Math.min(10, 20));


        // 4. Math.pow()
        // Raises a number to a specified power.
        // Example: 2 raised to the power of 3 is 8.
        System.out.println("Math.pow(): " + Math.pow(2, 3));


        // 5. Math.sqrt()
        // Returns the square root of a number.
        // Example: the square root of 25 is 5.
        System.out.println("Math.sqrt(): " + Math.sqrt(25));


        // 6. Math.round()
        // Rounds a decimal number to the nearest whole number.
        // Example: 4.6 is rounded to 5.
        System.out.println("Math.round(): " + Math.round(4.6));


        // 7. Math.ceil()
        // Rounds a decimal number UP to the next whole number.
        // Example: 4.2 becomes 5.0.
        System.out.println("Math.ceil(): " + Math.ceil(4.2));


        // 8. Math.floor()
        // Rounds a decimal number DOWN to the previous whole number.
        // Example: 4.8 becomes 4.0.
        System.out.println("Math.floor(): " + Math.floor(4.8));


        // 9. Math.random()
        // Generates a random decimal number from 0.0 (inclusive)
        // to 1.0 (exclusive).
        System.out.println("Math.random(): " + Math.random());


        // 10. Math.log()
        // Returns the natural logarithm of a number using base e.
        // Example: log of 10.
        System.out.println("Math.log(): " + Math.log(10));


        // 11. Math.log10()
        // Returns the logarithm of a number using base 10.
        // Example: log base 10 of 100 is 2.
        System.out.println("Math.log10(): " + Math.log10(100));


        // 12. Math.exp()
        // Returns e raised to the power of a number.
        // Example: e raised to the power of 2.
        System.out.println("Math.exp(): " + Math.exp(2));


        // 13. Math.sin()
        // Returns the sine of an angle.
        // The angle must be given in radians.
        // Example: sine of 90 degrees converted to radians.
        System.out.println("Math.sin(): " + Math.sin(Math.toRadians(90)));


        // 14. Math.cos()
        // Returns the cosine of an angle.
        // The angle must be given in radians.
        // Example: cosine of 60 degrees converted to radians.
        System.out.println("Math.cos(): " + Math.cos(Math.toRadians(60)));


        // 15. Math.tan()
        // Returns the tangent of an angle.
        // The angle must be given in radians.
        // Example: tangent of 45 degrees converted to radians.
        System.out.println("Math.tan(): " + Math.tan(Math.toRadians(45)));

    }
}
