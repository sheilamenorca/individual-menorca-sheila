package com.joysistvi.stage1.day3;

public class VariableThursday {
    public static void main(String[] args) {
        // initialization
        String timba = "tubig";
        int age = 20;
        String address = "Taguig City";

        // multiple variables with similar datatypes
        String pet = "aj", pet2 = "chuchu", pet3 = "tine";
        System.out.println(address);

        // declaration
        float temp;

        // assign value
        temp = 37.5f;

        System.out.println("Temperature: " + temp);
        System.out.println("Age: " + age);

        String firstName = "Sheila";
        String middleInitial = "C.";
        String lastName = "Menorca";

        System.out.println("Fullname: "+ lastName + ", " + firstName + " " + middleInitial);

    }
}
